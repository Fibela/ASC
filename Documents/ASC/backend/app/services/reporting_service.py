# ── PIIL signing helpers ───────────────────────────────────────────────────────

def _sha3_512_hex(data: dict) -> str:
    payload = json.dumps(data, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha3_512(payload).hexdigest()


def _sign_report(hash_hex: str) -> tuple[str, str]:
    """
    Sign hash_hex with SPECTER_SIGNING_PRIVATE_KEY.
    Returns (signature_b64, pubkey_fingerprint).
    Falls back to a deterministic placeholder when no key is configured
    (dev/test environments) — clearly marked as UNSIGNED.
    """
    private_key_b64 = _s.SPECTER_SIGNING_PRIVATE_KEY
    public_key_b64 = _s.SPECTER_SIGNING_PUBLIC_KEY

    if not private_key_b64:
        placeholder = base64.b64encode(b"PIIL-UNSIGNED-NO-KEY-CONFIGURED").decode()
        return placeholder, "0000000000000000"

    try:
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
        priv_bytes = base64.b64decode(private_key_b64)
        key = Ed25519PrivateKey.from_private_bytes(priv_bytes)
        sig = base64.b64encode(key.sign(hash_hex.encode())).decode()

        # Fingerprint: first 16 hex chars of SHA3-512 of the raw public key bytes
        if public_key_b64:
            pub_bytes = base64.b64decode(public_key_b64)
            fp = hashlib.sha3_512(pub_bytes).hexdigest()[:16]
        else:
            fp = "unknown"
        return sig, fp
    except Exception as exc:
        log.warning("PIIL signing failed — report will be UNSIGNED: %s", exc)
        placeholder = base64.b64encode(b"PIIL-SIGN-ERROR").decode()
        return placeholder, "error"


def verify_report_signature(report: ExecutiveReport) -> bool:
    """
    Verify the Ed25519 signature on an ExecutiveReport.
    Returns True only if the hash matches canonical_data AND the signature
    is cryptographically valid against SPECTER_SIGNING_PUBLIC_KEY.
    """
    if not report.is_hash_valid():
        return False

    public_key_b64 = _s.SPECTER_SIGNING_PUBLIC_KEY
    if not public_key_b64:
        return False

    try:
        from cryptography.exceptions import InvalidSignature
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
        pub_bytes = base64.b64decode(public_key_b64)
        pub_key = Ed25519PublicKey.from_public_bytes(pub_bytes)
        sig = base64.b64decode(report.signature_ed25519)
        pub_key.verify(sig, report.hash_sha3_512.encode())
        return True
    except Exception:
        return False


# ── KPI aggregation helpers ───────────────────────────────────────────────────

async def _incident_kpis(
    db: AsyncSession, start: datetime, end: datetime
) -> dict[str, Any]:
    """Aggregate incident KPIs within [start, end)."""

    # Total in period (detected_at within window)
    total_r = await db.execute(
        select(func.count()).select_from(Incident)
        .where(Incident.detected_at >= start, Incident.detected_at < end)
    )
    total = total_r.scalar_one()

    # Closed in period
    closed_r = await db.execute(
        select(func.count()).select_from(Incident)
        .where(Incident.closed_at >= start, Incident.closed_at < end)
    )
    closed = closed_r.scalar_one()

    # SLA breaches (detected in period + breached)
    breach_r = await db.execute(
        select(func.count()).select_from(Incident)
        .where(
            Incident.detected_at >= start,
            Incident.detected_at < end,
            Incident.sla_breach.is_(True),
        )
    )
    sla_breach = breach_r.scalar_one()

    # Avg MTTD/MTTC/MTTR for incidents closed in period
    mttd_r = await db.execute(
        select(func.avg(Incident.mttd_minutes))
        .where(Incident.closed_at >= start, Incident.closed_at < end)
        .where(Incident.mttd_minutes.isnot(None))
    )
    avg_mttd = mttd_r.scalar_one()

    mttc_r = await db.execute(
        select(func.avg(Incident.mttc_minutes))
        .where(Incident.closed_at >= start, Incident.closed_at < end)
        .where(Incident.mttc_minutes.isnot(None))
    )
    avg_mttc = mttc_r.scalar_one()

    mttr_r = await db.execute(
        select(func.avg(Incident.mttr_minutes))
        .where(Incident.closed_at >= start, Incident.closed_at < end)
        .where(Incident.mttr_minutes.isnot(None))
    )
    avg_mttr = mttr_r.scalar_one()

    # By severity
    sev_r = await db.execute(
        select(Incident.severity, func.count())
        .where(Incident.detected_at >= start, Incident.detected_at < end)
        .group_by(Incident.severity)
    )
    by_severity = {row[0]: row[1] for row in sev_r.all()}

    # By status (open at end of period = not closed/dismissed before end)
    status_r = await db.execute(
        select(Incident.status, func.count())
        .where(Incident.detected_at >= start, Incident.detected_at < end)
        .group_by(Incident.status)
    )
    by_status = {row[0]: row[1] for row in status_r.all()}

    return {
        "total": total,
        "closed": closed,
        "sla_breach_count": sla_breach,
        "avg_mttd_minutes": round(avg_mttd, 1) if avg_mttd is not None else None,
        "avg_mttc_minutes": round(avg_mttc, 1) if avg_mttc is not None else None,
        "avg_mttr_minutes": round(avg_mttr, 1) if avg_mttr is not None else None,
        "by_severity": by_severity,
        "by_status": by_status,
    }


async def _campaign_kpis(
    db: AsyncSession, start: datetime, end: datetime
) -> dict[str, Any]:
    """Aggregate correlation campaign KPIs."""
    campaign_r = await db.execute(
        select(func.count()).select_from(CorrelationCluster)
        .where(
            CorrelationCluster.is_campaign.is_(True),
            CorrelationCluster.first_seen >= start,
            CorrelationCluster.first_seen < end,
        )
    )
    campaigns = campaign_r.scalar_one()

    active_r = await db.execute(
        select(func.count()).select_from(CorrelationCluster)
        .where(
            CorrelationCluster.is_campaign.is_(True),
            CorrelationCluster.status == "active",
        )
    )
    active_campaigns = active_r.scalar_one()

    # Critical clusters
    crit_r = await db.execute(
        select(func.count()).select_from(CorrelationCluster)
        .where(
            CorrelationCluster.severity == "critical",
            CorrelationCluster.first_seen >= start,
            CorrelationCluster.first_seen < end,
        )
    )
    critical_clusters = crit_r.scalar_one()

    return {
        "new_campaigns": campaigns,
        "active_campaigns": active_campaigns,
        "critical_clusters": critical_clusters,
    }


async def _hunting_kpis(
    db: AsyncSession, start: datetime, end: datetime
) -> dict[str, Any]:
    """Aggregate threat hunting KPIs."""
    total_r = await db.execute(
        select(func.count()).select_from(Hunt)
        .where(Hunt.created_at >= start, Hunt.created_at < end)
    )
    total_hunts = total_r.scalar_one()

    findings_r = await db.execute(
        select(func.count()).select_from(HuntFinding)
        .where(HuntFinding.created_at >= start, HuntFinding.created_at < end)
        .where(HuntFinding.is_false_positive.is_(False))
    )
    findings = findings_r.scalar_one()

    critical_r = await db.execute(
        select(func.count()).select_from(HuntFinding)
        .where(
            HuntFinding.severity == "critical",
            HuntFinding.created_at >= start,
            HuntFinding.created_at < end,
            HuntFinding.is_false_positive.is_(False),
        )
    )
    critical_findings = critical_r.scalar_one()

    return {
        "total_hunts": total_hunts,
        "confirmed_findings": findings,
        "critical_findings": critical_findings,
    }


async def _soar_kpis(
    db: AsyncSession, start: datetime, end: datetime
) -> dict[str, Any]:
    """Aggregate SOAR auto-trigger KPIs."""
    fired_r = await db.execute(
        select(func.count()).select_from(PlaybookTrigger)
        .where(
            PlaybookTrigger.last_triggered_at >= start,
            PlaybookTrigger.last_triggered_at < end,
        )
    )
    triggers_fired = fired_r.scalar_one()

    alert_r = await db.execute(
        select(func.count()).select_from(Alert)
        .where(Alert.detected_at >= start, Alert.detected_at < end)
    )
    alerts_in_period = alert_r.scalar_one()

    return {
        "soar_triggers_fired": triggers_fired,
        "alerts_in_period": alerts_in_period,
    }


# ── Report generation ──────────────────────────────────────────────────────────

async def generate_report(
    db: AsyncSession,
    *,
    report_type: str,
    period: str,
    period_start: datetime,
    period_end: datetime,
    generated_by: str,
    title: str | None = None,
) -> ExecutiveReport:
    """
    Aggregate KPIs for the requested period, seal with PIIL signature, persist.

    The canonical_data dict includes every sub-domain KPI plus metadata.
    The SHA3-512 hash + Ed25519 signature are computed over canonical_data.
    """
    now = datetime.now(timezone.utc)

    # ── Gather domain KPIs ──
    inc_kpis = await _incident_kpis(db, period_start, period_end)
    camp_kpis = await _campaign_kpis(db, period_start, period_end)
    hunt_kpis = await _hunting_kpis(db, period_start, period_end)
    soar_kpis = await _soar_kpis(db, period_start, period_end)

    report_title = title or (
        f"PremosCorp ASC — {report_type.replace('_', ' ').title()} "
        f"({period_start.date()} → {period_end.date()})"
    )

    # ── Build canonical payload ──
    canonical: dict[str, Any] = {
        "report_id": str(uuid.uuid4()),  # baked in before signing
        "report_type": report_type,
        "period": period,
        "title": report_title,
        "generated_by": generated_by,
        "generated_at": now.isoformat(),
        "period_start": period_start.isoformat(),
        "period_end": period_end.isoformat(),
        "incidents": inc_kpis,
        "campaigns": camp_kpis,
        "hunting": hunt_kpis,
        "soar": soar_kpis,
        "platform": "PremosCorp ASC",
        "piil_version": "1.0",
    }

    # ── PIIL seal ──
    hash_hex = _sha3_512_hex(canonical)
    signature, fp = _sign_report(hash_hex)

    report = ExecutiveReport(
        id=canonical["report_id"],
        report_type=report_type,
        period=period,
        title=report_title,
        generated_by=generated_by,
        period_start=period_start,
        period_end=period_end,
        total_incidents=inc_kpis["total"],
        closed_incidents=inc_kpis["closed"],
        sla_breach_count=inc_kpis["sla_breach_count"],
        campaign_count=camp_kpis["new_campaigns"],
        avg_mttd_minutes=inc_kpis["avg_mttd_minutes"],
        avg_mttc_minutes=inc_kpis["avg_mttc_minutes"],
        avg_mttr_minutes=inc_kpis["avg_mttr_minutes"],
        canonical_data=canonical,
        hash_sha3_512=hash_hex,
        signature_ed25519=signature,
        pubkey_fingerprint=fp,
        signature_valid=bool(_s.SPECTER_SIGNING_PRIVATE_KEY),
        created_at=now,
    )

    db.add(report)
    await db.commit()
    await db.refresh(report)

    log_security_action(
        "executive_report_generated",
        actor=generated_by,
        resource_id=report.id,
        detail={
            "report_type": report_type,
            "period": period,
            "hash_prefix": hash_hex[:16],
            "signed": bool(_s.SPECTER_SIGNING_PRIVATE_KEY),
        },
    )
    log.info(
        "executive_report id=%s type=%s period=%s→%s signed=%s",
        report.id, report_type,
        period_start.date(), period_end.date(),
        bool(_s.SPECTER_SIGNING_PRIVATE_KEY),
    )
    return report


async def verify_report(db: AsyncSession, report_id: str) -> dict[str, Any]:
    """
    Re-verify a stored report's hash + signature.
    Updates signature_valid cache and last_verified_at.
    Returns a structured verification result.
    """
    result = await db.execute(
        select(ExecutiveReport).where(ExecutiveReport.id == report_id)
    )
    report = result.scalar_one_or_none()
    if report is None:
        raise ValueError(f"Report {report_id} not found")

    hash_ok = report.is_hash_valid()
    sig_ok = verify_report_signature(report)
    overall = hash_ok and sig_ok

    now = datetime.now(timezone.utc)
    report.signature_valid = overall
    report.last_verified_at = now
    await db.commit()

    log_security_action(
        "executive_report_verified",
        actor="system",
        resource_id=report_id,
        detail={"hash_valid": hash_ok, "sig_valid": sig_ok},
    )

    return {
        "report_id": report_id,
        "hash_valid": hash_ok,
        "signature_valid": sig_ok,
        "overall_valid": overall,
        "pubkey_fingerprint": report.pubkey_fingerprint,
        "verified_at": now.isoformat(),
    }


async def get_report(db: AsyncSession, report_id: str) -> ExecutiveReport | None:
    result = await db.execute(
        select(ExecutiveReport).where(ExecutiveReport.id == report_id)
    )
    return result.scalar_one_or_none()


async def list_reports(
    db: AsyncSession,
    *,
    report_type: str | None = None,
    limit: int = 50,
    offset: int = 0,
) -> list[ExecutiveReport]:
    q = select(ExecutiveReport).order_by(ExecutiveReport.created_at.desc())
    if report_type:
        q = q.where(ExecutiveReport.report_type == report_type)
    q = q.limit(limit).offset(offset)
    result = await db.execute(q)
    return list(result.scalars().all())


async def get_reporting_summary(db: AsyncSession) -> dict[str, Any]:
    """Dashboard summary: report counts, last generated, unsigned count."""
    total_r = await db.execute(select(func.count()).select_from(ExecutiveReport))
    total = total_r.scalar_one()

    unsigned_r = await db.execute(
        select(func.count()).select_from(ExecutiveReport)
        .where(ExecutiveReport.signature_valid.is_(False))
    )
    unsigned = unsigned_r.scalar_one()

    by_type_r = await db.execute(
        select(ExecutiveReport.report_type, func.count())
        .group_by(ExecutiveReport.report_type)
    )
    by_type = {row[0]: row[1] for row in by_type_r.all()}

    latest_r = await db.execute(
        select(ExecutiveReport).order_by(ExecutiveReport.created_at.desc()).limit(1)
    )
    latest = latest_r.scalar_one_or_none()

    return {
        "total_reports": total,
        "unsigned_reports": unsigned,
        "by_type": by_type,
        "last_generated_at": latest.created_at.isoformat() if latest else None,
        "last_report_id": latest.id if latest else None,
    }
