"""
Executive Reporting Service — P29-B / PIIL

Generates signed executive intelligence reports aggregating KPIs from every
ASC domain: incidents (P28), correlation campaigns (P27), threat hunting (P22),
SOAR actions (P25), and threat intelligence (P21).

PIIL — Premos Incident Intelligence Layer
-----------------------------------------
Every generated report is sealed with:
  1. SHA3-512 hash of the canonical JSON payload
  2. Ed25519 signature using SPECTER_SIGNING_PRIVATE_KEY

This provides Executive Authenticity: any third party with the Premos public key
can verify offline that the report was generated by PremosCorp ASC and has not
been tampered with — differentiating from unauthenticated dashboards exported
from Falcon, SentinelOne, or similar.

Security posture
----------------
- All aggregation queries are READ-ONLY SELECT
- Private key is never stored in the report — only the public key fingerprint
- Signature verification is self-contained: canonical_data + hash + signature
- signature_valid is a cache flag only; always re-verify for forensic purposes
"""
